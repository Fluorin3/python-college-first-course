# ДЗ 2, задача 14 «Оценка за практическую работу» (★★★)
# Главы: 2.3, 2.4, 2.5
#
# В онлайн-школе за практическую работу ставят от 0 до 10 баллов. Если работа сдана в срок, оценка
# зависит от баллов: 9–10 — «Оценка: 5», 7–8 — «Оценка: 4», 5–6 — «Оценка: 3», меньше 5 —
# «Работа не зачтена». Если работа сдана после срока, при 5 баллах и больше ставится «Оценка: 3»,
# иначе — «Работа не зачтена». Вводятся ответ, сдана ли работа в срок («да» или «нет»), и баллы.
# Если баллы меньше 0 или больше 10, выведите «Ошибка ввода».
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     да
#     10
#   в терминале:
#     Сдана в срок (да/нет): да
#     Баллы: 10
#     Оценка: 5
# Пример 2
#   ввод:
#     да
#     7
#   в терминале:
#     Сдана в срок (да/нет): да
#     Баллы: 7
#     Оценка: 4
# Пример 3
#   ввод:
#     да
#     4
#   в терминале:
#     Сдана в срок (да/нет): да
#     Баллы: 4
#     Работа не зачтена
# Пример 4
#   ввод:
#     нет
#     9
#   в терминале:
#     Сдана в срок (да/нет): нет
#     Баллы: 9
#     Оценка: 3
# Пример 5
#   ввод:
#     нет
#     3
#   в терминале:
#     Сдана в срок (да/нет): нет
#     Баллы: 3
#     Работа не зачтена
# Пример 6
#   ввод:
#     да
#     12
#   в терминале:
#     Сдана в срок (да/нет): да
#     Баллы: 12
#     Ошибка ввода

# Решение
deadline = input()
points = int(input())
grade = 0

if points < 0 or points > 10:
    raise Warning("Ошибка ввода баллов!")

if deadline not in ['да', 'нет']:
    raise Warning("Ошибка ввода срока!")

if deadline == "да":
    if points >= 9:
        grade = 5
    elif points in [7, 8]:
        grade = 4
    elif points in [5, 6]:
        grade = 3
    else:
        pass

elif deadline == 'нет':
    if points >= 5:
        grade = 3
    else:
        pass

print(f"Сдана в срок (да/нет): {deadline}")
print(f"Баллы: {points}")

if grade != 0:
    print(f"Оценка: {grade}")

else:
    print("Работа не зачтена")